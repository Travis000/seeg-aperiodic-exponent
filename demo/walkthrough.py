"""End-to-end walkthrough on synthetic data: every step, with its numbers shown.

Run it::

    python demo/walkthrough.py

Each section states what is being computed, prints the intermediate quantities,
and where a ground truth exists, prints that too. The data are generated by
``demo/synthetic.py`` and are not study data; the numbers below are properties
of the estimators, not results.
"""

